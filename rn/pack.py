"""rn pack: the offline asset pack that ships inside rn: sound effects, fonts, colour looks and icons.

Everything here is licence-clean (CC0 sounds, OFL / Apache-2.0 fonts, ISC icons, looks generated by rn's own code) and
works without a network. rn/packs/catalog.json lists every item; sound effects carry measured onset and peak times, so
`rn edit EDL hits <id>` can put a whoosh's peak on the cut without being told where it is. Attribution:
rn/packs/LICENSES.md. Rebuild with scripts/build_pack.py in the repository.

Ids: sound effects `<category>/<name>` (whoosh/air-1), fonts `font/<name>`, looks `look/<name>`, icons `icon/<lucide name>`.
Looks and icons are generated on first use into the cache (RN_CACHE, default ~/.cache/rn/pack).
"""
