def _cache() -> Path:
    from . import __version__
    root = Path(os.environ['RN_CACHE']) if os.environ.get('RN_CACHE') else Path.home() / '.cache' / 'rn'
    return root / 'pack' / __version__  # a look's recipe can change between versions


@lru_cache(maxsize=1)
def catalog() -> list[dict]:
    items = json.loads((PACK / 'catalog.json').read_text(encoding='utf-8'))['items']
    return items + [{'id': f'look/{name}', 'kind': 'look', 'category': 'look', 'tags': recipe['tags'],
                     'description': recipe['what'], 'license': 'MIT (generated by rn)', 'source': 'rn/pack.py', 'author': 'Renoise'}
                    for name, recipe in LOOKS.items()]


@lru_cache(maxsize=1)
def _icons() -> dict:
    return json.loads((PACK / 'icons' / 'lucide.json').read_text(encoding='utf-8'))


def is_pack_id(text: str) -> bool:
    text = text.removeprefix('pack:')
    return '/' in text and not Path(text).suffix and not Path(text).exists()


def find(item_id: str) -> dict:
    item_id = item_id.removeprefix('pack:')
    if item_id.startswith('icon/'):
        name = item_id[5:]
        icons = _icons()
        if name not in icons['icons']:
            close = [n for n in icons['icons'] if name in n][:8]
            raise RnError(f'{item_id}: no such icon' + (f' (did you mean {", ".join("icon/" + n for n in close)}?)' if close else
                                                        '; rn pack list --kind icon --search WORD'))
        return {'id': item_id, 'kind': 'icon', 'category': 'icon', 'tags': icons['tags'].get(name, []),
                'license': 'ISC', 'source': f'lucide-static {icons["version"]}', 'author': 'Lucide contributors'}
    for item in catalog():
        if item['id'] == item_id:
            return item
    close = [i['id'] for i in catalog() if item_id.split('/')[-1] in i['id']][:8]
    raise RnError(f'{item_id}: not in the pack' + (f' (did you mean {", ".join(close)}?)' if close else '; rn pack list'))


def path_of(item_id: str) -> Path:
    """Absolute path of an item's file; looks and icons are generated into the cache on first use."""
    item = find(item_id)
    if item['kind'] == 'look':
        out = _cache() / 'looks' / f'{item["id"][5:]}.cube'
        if not out.exists():
            out.parent.mkdir(parents=True, exist_ok=True)
            tmp = out.with_suffix('.tmp')
            tmp.write_text(cube_text(item['id'][5:]), encoding='ascii')
            tmp.replace(out)
        return out
    if item['kind'] == 'icon':
        out = _cache() / 'icons' / f'{item["id"][5:]}.svg'
        if not out.exists():
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_text(icon_svg(item['id'][5:]), encoding='utf-8')
        return out
    return (PACK / item['file']).resolve()


def icon_svg(name: str, color: str = 'currentColor', stroke_width: float = 2, size: int = 24) -> str:
    body = ''.join('<' + tag + ''.join(f' {k}="{v}"' for k, v in attrs.items()) + '/>' for tag, attrs in _icons()['icons'][name])
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" viewBox="0 0 24 24" fill="none" '
            f'stroke="{color}" stroke-width="{stroke_width}" stroke-linecap="round" stroke-linejoin="round">{body}</svg>\n')


def font_dir() -> Path:
    return (PACK / 'fonts').resolve()


def font_faces() -> list[dict]:
    """[{family, file (absolute), weight ("400" or "100 900"), style}] for every pack font: @font-face / FontFace input."""
    faces = []
    for item in catalog():
        if item['kind'] == 'font':
            weights = item['weights']
            faces.append({'family': item['family'], 'file': str((PACK / item['file']).resolve()),
                          'weight': f'{weights[0]} {weights[-1]}' if item.get('variable') else str(weights[0]), 'style': 'normal'})
    return faces


# ---- looks: deterministic colour recipes baked into 33^3 .cube LUTs (sRGB in, sRGB out) ----

def _luma(rgb):
    return rgb @ np.array([0.2126, 0.7152, 0.0722])


def _sat(rgb, amount):
    y = _luma(rgb)[:, None]
    return y + (rgb - y) * amount


def _contrast(rgb, amount, pivot=0.5):
    """S-curve around pivot: amount > 1 adds contrast (smooth, keeps 0 and 1 in place)."""
    x = np.clip(rgb, 0, 1)
    low = pivot * (x / pivot) ** amount
    high = 1 - (1 - pivot) * ((1 - x) / (1 - pivot)) ** amount
    return np.where(x < pivot, low, high)


def _levels(rgb, black=0.0, white=1.0):
    return black + rgb * (white - black)


def _tint(rgb, shadows=(0, 0, 0), highlights=(0, 0, 0), mids=(0, 0, 0)):
    """Add colour per zone, weighted by luma: shadows fade out by mid grey, highlights fade in from it."""
    y = np.clip(_luma(rgb), 0, 1)[:, None]
    w_s = np.clip(1 - y / 0.5, 0, 1) ** 1.5
    w_h = np.clip((y - 0.5) / 0.5, 0, 1) ** 1.5
    w_m = 1 - w_s - w_h
    return rgb + w_s * np.array(shadows) + w_h * np.array(highlights) + w_m * np.array(mids)


def _gain(rgb, r=1.0, g=1.0, b=1.0):
    return rgb * np.array([r, g, b])


def _gamma(rgb, g):
    return np.clip(rgb, 0, 1) ** g


def _mono(rgb, weights=(0.2126, 0.7152, 0.0722)):
    y = rgb @ np.array(weights)
    return np.repeat(y[:, None], 3, axis=1)


def _skin_protect(rgb, graded, amount=0.6):
    """Blend back toward the original on orange-ish (skin) hues so a strong tint keeps faces natural."""
    r, g, b = rgb[:, 0], rgb[:, 1], rgb[:, 2]
    skin = np.clip((r - g) * 4, 0, 1) * np.clip((g - b) * 4, 0, 1) * np.clip(1 - np.abs((r - g) / (r - b + 1e-6) - 0.4) * 2.5, 0, 1)
    w = (skin * amount)[:, None]
    return graded * (1 - w) + rgb * w


