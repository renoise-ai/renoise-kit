def lut_values(name: str, size: int = LUT_SIZE) -> np.ndarray:
    """(size^3, 3) output RGB for the .cube grid, red changing fastest."""
    axis = np.linspace(0, 1, size)
    b, g, r = np.meshgrid(axis, axis, axis, indexing='ij')
    grid = np.stack([r.ravel(), g.ravel(), b.ravel()], axis=1)
    return np.clip(LOOKS[name]['f'](grid), 0, 1)


def cube_text(name: str, size: int = LUT_SIZE) -> str:
    values = lut_values(name, size)
    lines = [f'TITLE "rn {name}"', f'# {LOOKS[name]["what"]}', f'LUT_3D_SIZE {size}', 'DOMAIN_MIN 0 0 0', 'DOMAIN_MAX 1 1 1']
    lines += [f'{r:.5f} {g:.5f} {b:.5f}' for r, g, b in values]
    return '\n'.join(lines) + '\n'


# ---- commands ----

def list_command(kind: str | None = None, category: str | None = None, search: str | None = None, limit: int = 60) -> dict:
    if kind == 'icon':
        icons = _icons()
        words = (search or '').lower().split()
        names = [n for n in icons['icons'] if all(w in n or any(w in t for t in icons['tags'].get(n, [])) for w in words)]
        return {'kind': 'icon', 'total': len(names), 'items': [{'id': f'icon/{n}', 'tags': icons['tags'].get(n, [])[:6]} for n in names[:limit]]}
    items = catalog()
    if kind:
        items = [i for i in items if i['kind'] == kind]
    if category:
        items = [i for i in items if i['category'] == category]
    for word in (search or '').lower().split():
        items = [i for i in items if word in i['id'] or any(word in t for t in i.get('tags', [])) or word in i.get('description', '').lower()]
    categories: dict[str, int] = {}
    for item in items:
        categories[f'{item["kind"]}:{item["category"]}'] = categories.get(f'{item["kind"]}:{item["category"]}', 0) + 1
    return {'total': len(items), 'categories': categories, 'items': items[:limit], 'icons': len(_icons()['icons'])}


def get_command(ids: list[str], out: str, color: str = 'currentColor', stroke_width: float = 2) -> dict:
    if not ids:
        raise RnError('rn pack get ID... -o DIR: give item ids from rn pack list')
    out_dir = Path(out)
    out_dir.mkdir(parents=True, exist_ok=True)
    written = []
    for item_id in ids:
        item = find(item_id)
        if item['kind'] == 'icon':
            dest = out_dir / f'{item["id"][5:]}.svg'
            dest.write_text(icon_svg(item['id'][5:], color, stroke_width), encoding='utf-8')
        else:
            src = path_of(item_id)
            dest = out_dir / (src.name if item['kind'] == 'font' else item['id'].replace('/', '-') + src.suffix)
            shutil.copyfile(src, dest)
        written.append({'id': item['id'], 'path': str(dest)})
    return {'written': written}


def path_command(ids: list[str]) -> dict:
    if not ids:
        raise RnError('rn pack path ID...: give item ids from rn pack list (or "licenses")')
    paths = [str((PACK / 'LICENSES.md').resolve()) if i == 'licenses' else str(path_of(i)) for i in ids]
    return {'path': '\n'.join(paths), 'paths': paths}


def show_command(ids: list[str]) -> dict:
    if len(ids) != 1:
        raise RnError('rn pack show ID: one item id')
    item = dict(find(ids[0]))
    if item['kind'] == 'look':
        item['path'] = str(path_of(item['id']))
    return {'item': item}


def summary_lines(result: dict) -> list[str]:
    if 'written' in result:
        return [f'{w["id"]} -> {w["path"]}' for w in result['written']]
    if 'path' in result:
        return [result['path']]
    if 'item' in result:
        return [json.dumps(result['item'], indent=1, ensure_ascii=False)]
    if result.get('kind') == 'icon':
        lines = [f'{i["id"]:34} {", ".join(i["tags"])}' for i in result['items']]
        return lines + [f'{result["total"]} icons match' + (f' (first {len(result["items"])})' if result['total'] > len(result['items']) else '')
                        + '; rn pack get icon/<name> -o icons/ writes an SVG']
    lines = []
    for item in result['items']:
        if item['kind'] == 'sfx':
            detail = f'{item["duration"]:5.2f}s  peak {item["peak"]:.2f}s  {", ".join(item["tags"][:4])}'
        elif item['kind'] == 'font':
            detail = f'{item["family"]}  weights {item["weights"][0]}' + (f'-{item["weights"][-1]}' if len(item['weights']) > 1 else '') + f'  {item["description"]}'
        else:
            detail = item['description']
        lines.append(f'{item["id"]:30} {detail}')
    shown = len(result['items'])
    cats = '  '.join(f'{k}={v}' for k, v in result['categories'].items())
    lines.append(f'{result["total"]} items' + (f' (first {shown}; --limit or --search to narrow)' if result['total'] > shown else '')
                 + f'; {result["icons"]} icons (--kind icon)')
    if not result.get('items') or result['total'] > shown:
        lines.append(cats)
    return lines
