def test_hits_takes_a_pack_id_and_lands_its_peak_on_the_cut(tmp_path):
    clips = [{'id': 'a', 'color': 'red', 'duration': 1}, {'id': 'b', 'color': 'blue', 'duration': 1}]
    edl = write_edl(tmp_path, {'version': 2, 'output': {'width': 160, 'height': 120, 'fps': 24}, 'tracks': [{'clips': clips}]})
    assert rn('edit', edl, 'hits', 'boom/explosion-1', '--at', 'cuts') == 0
    item = json.loads(edl.read_text())['audio'][0]
    peak = pack.find('boom/explosion-1')['peak']
    assert item['src'] == 'sfx/boom-explosion-1.ogg' and item['pivot'] == peak and (tmp_path / item['src']).exists()
    assert rn('assemble', edl, '-o', tmp_path / 'out.mp4') == 0
    raw = subprocess.run(['ffmpeg', '-v', 'error', '-i', str(tmp_path / 'out.mp4'), '-ac', '1', '-ar', '1000', '-f', 'f32le', '-'],
                         capture_output=True, check=True).stdout
    env = np.abs(np.frombuffer(raw, dtype=np.float32))
    loudest = np.argmax(np.convolve(env, np.ones(10), 'same')) / 1000
    assert abs(loudest - 1.0) < 0.06  # the explosion's peak sits on the cut at 1 s


def test_looks_are_cube_luts_that_do_what_they_say(tmp_path):
    lut = pack.path_of('look/mono-contrast')
    text = lut.read_text().splitlines()
    assert 'LUT_3D_SIZE 33' in text and len([l for l in text if l[:1].isdigit()]) == 33 ** 3
    bars = tmp_path / 'bars.png'
    ffmpeg('-f', 'lavfi', '-i', 'smptebars=s=160x90', '-frames:v', '1', str(bars))
    out = tmp_path / 'mono.png'
    ffmpeg('-i', str(bars), '-vf', f'lut3d=file={lut.as_posix()}', str(out))
    rgb = np.asarray(Image.open(out).convert('RGB')).astype(int)
    assert np.abs(rgb[..., 0] - rgb[..., 2]).max() <= 2  # no colour left
    warm = np.asarray(Image.open(_graded(tmp_path, bars, 'warm-golden')).convert('RGB')).astype(float)
    before = np.asarray(Image.open(bars).convert('RGB')).astype(float)
    assert (warm[..., 0] - warm[..., 2]).mean() > (before[..., 0] - before[..., 2]).mean() + 5


def _graded(tmp_path, src, look):
    out = tmp_path / f'{look}.png'
    ffmpeg('-i', str(src), '-vf', f'lut3d=file={pack.path_of("look/" + look).as_posix()}', str(out))
    return out


@pytest.mark.skipif(not has_filter('subtitles'), reason='ffmpeg without libass')
def test_pack_font_renders_in_burned_subtitles(tmp_path):
    def burn(font: str) -> np.ndarray:
        ass = tmp_path / f'{font.replace(" ", "")}.ass'
        ass.write_text('[Script Info]\nPlayResX: 320\nPlayResY: 180\n\n[V4+ Styles]\nFormat: Name, Fontname, Fontsize, PrimaryColour, '
                       'Bold, Alignment, MarginV\nStyle: Default,' + font + ',60,&H00FFFFFF,0,5,0\n\n[Events]\n'
                       'Format: Layer, Start, End, Style, Text\nDialogue: 0,0:00:00.00,0:00:01.00,Default,WIDE MMM\n', encoding='utf-8')
        edl = write_edl(tmp_path, {'version': 2, 'output': {'width': 320, 'height': 180, 'fps': 10},
                                   'tracks': [{'clips': [{'color': 'black', 'duration': 1}]}], 'subtitles': {'file': ass.name}},
                        name=f'{ass.stem}.json')
        assert rn('assemble', edl, '-o', tmp_path / f'{ass.stem}.mp4') == 0
        assert rn('frame', tmp_path / f'{ass.stem}.mp4', '--index', 5, '-o', tmp_path / f'{ass.stem}.png') == 0
        lit = np.asarray(Image.open(tmp_path / f'{ass.stem}.png').convert('L')) > 128
        cols = np.where(lit.any(axis=0))[0]
        return cols.max() - cols.min()
    # Bebas Neue (pack only) is far narrower than whatever the system falls back to for an unknown family.
    assert burn('Bebas Neue') < 0.8 * burn('No Such Family Zz')


def test_wheel_ships_the_pack(tmp_path):
    from pathlib import Path
    import zipfile
    kit = Path(__file__).parents[1]
    subprocess.run(['uv', 'build', '--wheel', '--out-dir', str(tmp_path), str(kit)], check=True, capture_output=True)
    wheel = next(tmp_path.glob('renoise_kit-*.whl'))
    names = set(zipfile.ZipFile(wheel).namelist())
    shipped = {f'rn/packs/{i["file"]}' for i in pack.catalog() if 'file' in i}
    assert shipped <= names and {'rn/packs/catalog.json', 'rn/packs/LICENSES.md', 'rn/packs/icons/lucide.json'} <= names
    assert wheel.stat().st_size < 12_000_000
